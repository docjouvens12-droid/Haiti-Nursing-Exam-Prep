const videosById = new Map(studyVideos.map((video) => [video.id, video]));
const keyFor = (category: string, topic: string, subtopic: string) =>
  JSON.stringify([category, topic, subtopic]);
const videosBySubtopic = new Map(studyVideoAssignments.map((assignment) => [
  keyFor(assignment.category, assignment.topic, assignment.subtopic),
  assignment.videoIds.map((id) => {
    const video = videosById.get(id);
    if (!video || video.durationSeconds <= 0 || video.durationSeconds >= 900) {
      throw new Error(`Invalid study video: ${id}`);
    }
    return video;
  }),
]));
const noVideos: readonly StudyVideo[] = [];

export function getStudyVideos(category: string, topic: string, subtopic: string): readonly StudyVideo[] {
  return videosBySubtopic.get(keyFor(category, topic, subtopic)) ?? noVideos;
}

export function countVideoSubtopics(category: string, topic: string) {
  return studyVideoAssignments.filter((item) => item.category === category && item.topic === topic).length;
}
